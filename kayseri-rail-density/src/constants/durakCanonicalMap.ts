/**
 * Sadece DURAK_ID → kanonik ad. Excel/raw asla map’teyken kullanılmaz (yüzen nokta ID’ler Math.round).
 */
export function getCanonicalDurakAd(durakId: string | number, fallback = ''): string {
  const n = Number(durakId);
  const id = Number.isFinite(n) ? Math.round(n) : NaN;
  return DURAK_ID_CANONICAL_AD[id] ?? fallback;
}
